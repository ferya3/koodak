/** فاصله‌ی بین حروف و پهنای فاصله (به واحد بالا) */
export const LATIN_GAP = 16;
export const LATIN_SPACE = 44;

export const isLatinText = (s: string) => /^[A-Za-z0-9 ']+$/.test(s);

/** نقطه‌ی شروع هر ضربه (برای دایره‌ی سبز «از اینجا شروع کن») */
export function strokeStarts(d: string): [number, number][] {
  return [...d.matchAll(/M\s*(-?[\d.]+)[ ,]+(-?[\d.]+)/g)].map((m) => [Number(m[1]), Number(m[2])]);
}
